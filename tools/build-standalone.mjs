#!/usr/bin/env node
/* ════════════════════════════════════════════════════════════════════════
   build-standalone.mjs — emits WALL.html, the whole piece in one file.
   config.json, the pinned engine, voice, stream, card and feed are
   inlined byte-identical; a fetch shim serves config and the engine from
   the DOM. Everything else (reservoir) falls through and fails silently.
   For load-ins with no server: open the file, move it to the wall
   display, fullscreen.
   Usage: node tools/build-standalone.mjs [outPath]   (default ./WALL.html)
   ════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2] || join(root, 'WALL.html');

const cfgText = readFileSync(join(root, 'infinite/config.json'), 'utf8');
const cfg = JSON.parse(cfgText);
const engineName = cfg.engine.file.split('/').pop();
const eng = readFileSync(join(root, 'engine', engineName), 'utf8');
const voice = readFileSync(join(root, 'infinite/voice.js'), 'utf8');
const stream = readFileSync(join(root, 'infinite/stream.js'), 'utf8');
const card = readFileSync(join(root, 'infinite/card.js'), 'utf8');
const feed = readFileSync(join(root, 'infinite/feed.js'), 'utf8');
for (const [n, s] of [['engine', eng], ['voice', voice], ['stream', stream], ['card', card], ['feed', feed]])
  if (s.toLowerCase().includes('</script')) { console.error('FATAL: ' + n + ' contains </script'); process.exit(1); }

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>DITHERVOID</title>
<!-- INFINITE SCROLL · STANDALONE WALL FILE
     generated by tools/build-standalone.mjs · engine ${cfg.engine.commit}
     Open directly, move to the wall display (native mode, DPR 1),
     fullscreen. No server needed. -->
<style>
  html, body { margin: 0; padding: 0; background: #000; overflow: hidden;
               cursor: none; user-select: none; }
  ::-webkit-scrollbar { display: none; }
</style>
<script>window.PANDORA_PUBLIC = true;</script>
<script type="text/plain" id="is-config">${cfgText}</script>
<script type="text/plain" id="is-engine">${eng}</script>
<script>
(function () {
  var inline = {
    'config.json': 'is-config',
    '${cfg.engine.file}': 'is-engine'
  };
  var real = window.fetch ? window.fetch.bind(window) : null;
  window.fetch = function (url, opts) {
    var key = String(url).split('?')[0];
    if (inline[key]) return Promise.resolve(new Response(document.getElementById(inline[key]).textContent, { status: 200 }));
    if (real) return real(url, opts).catch(function () { return new Response('', { status: 404 }); });
    return Promise.resolve(new Response('', { status: 404 }));
  };
})();
</script>
</head>
<body>
<script>${voice}</script>
<script>${stream}</script>
<script>${card}</script>
<script>${feed}</script>
</body>
</html>
`;
writeFileSync(out, html);
console.log('WALL.html: ' + html.length + ' chars · engine ' + cfg.engine.commit + ' · qr ' + cfg.chrome.qr.base);
